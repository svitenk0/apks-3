// =============================================================================
// i2c_tx.v — передавач (Tx) одного байта I2C Master
// -----------------------------------------------------------------------------
// Лабораторна робота №3, варіант 20 (I2C, Verilog). Світенко П.І., КІ-408.
//
// Передає байт `din` старшим бітом уперед (MSB first) за 9 тактів SCL:
//   8 тактів даних + 9-й такт підтвердження (ACK), на якому передавач
//   відпускає SDA і зчитує відповідь веденого: SDA = 0 -> ACK, SDA = 1 -> NACK.
//
// Кожен такт SCL поділено на 4 фази (`phase`), які задає спільний генератор
// фаз у i2c_master. Дія виконується в момент імпульсу `qtick`:
//
//   phase | дія                                   | рівень SCL після дії
//   ------+---------------------------------------+---------------------
//     0   | виставити біт даних на SDA            | 0 (SDA змінюється лише при SCL=0)
//     1   | відпустити SCL (наростаючий фронт)    | 1
//     2   | середина SCL=1: зчитати ACK (9-й такт)| 1
//     3   | притиснути SCL до 0, зсув регістра    | 0
//
// Лінії шини — відкритий стік: вихід `*_oe = 1` притискає лінію до 0,
// `*_oe = 0` відпускає її (логічну 1 формує підтягувальний резистор).
// =============================================================================
`timescale 1ns / 1ps
`default_nettype none

module i2c_tx (
    input  wire       clk,      // системна тактова частота
    input  wire       rst_n,    // синхронне скидання, активний рівень 0
    input  wire       qtick,    // імпульс фази (1 такт clk), від генератора фаз
    input  wire [1:0] phase,    // номер фази, що виконується на цьому qtick
    input  wire       start,    // імпульс: почати передачу байта din
    input  wire [7:0] din,      // байт для передачі (адреса+R/W або дані)
    input  wire       sda_i,    // синхронізований стан лінії SDA
    output reg        scl_oe,   // 1 = притиснути SCL до 0
    output reg        sda_oe,   // 1 = притиснути SDA до 0
    output reg        busy,     // 1 = іде передача байта
    output reg        done,     // імпульс: байт і такт ACK завершено
    output reg        ack       // результат: 1 = ведений відповів ACK
);

    // ---- внутрішні регістри ----
    reg [7:0] shreg;   // зсувний регістр; на SDA завжди виставляється shreg[7]
    reg [3:0] bitn;    // номер поточного такту SCL: 0..7 — дані, 8 — ACK

    always @(posedge clk) begin
        if (!rst_n) begin
            scl_oe <= 1'b1;        // поза передачею SCL утримується в 0
            sda_oe <= 1'b0;
            busy   <= 1'b0;
            done   <= 1'b0;
            ack    <= 1'b0;
            shreg  <= 8'h00;
            bitn   <= 4'd0;
        end else begin
            done <= 1'b0;                          // done — одноклітинний імпульс

            if (start) begin
                // ---- завантаження байта; SCL вже в 0 (після START або ACK) ----
                shreg  <= din;
                bitn   <= 4'd0;
                busy   <= 1'b1;
                scl_oe <= 1'b1;
            end else if (busy && qtick) begin
                case (phase)
                    2'd0: // SCL = 0: виставляємо біт (0 -> притиснути, 1 -> відпустити);
                          // на такті ACK відпускаємо SDA, щоб ведений міг відповісти
                        sda_oe <= (bitn < 4'd8) ? ~shreg[7] : 1'b0;
                    2'd1: // наростаючий фронт SCL; ведений фіксує біт
                        scl_oe <= 1'b0;
                    2'd2: // середина високого рівня SCL: фіксуємо ACK
                        if (bitn == 4'd8) ack <= ~sda_i;
                    2'd3: begin // спадаючий фронт SCL, перехід до наступного біта
                        scl_oe <= 1'b1;
                        shreg  <= {shreg[6:0], 1'b0};
                        if (bitn == 4'd8) begin
                            busy <= 1'b0;
                            done <= 1'b1;
                        end else begin
                            bitn <= bitn + 4'd1;
                        end
                    end
                endcase
            end
        end
    end

endmodule

`default_nettype wire
